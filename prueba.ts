import { Injectable } from '@angular/core';
import { 
  ResponseDashboardCards, 
  ResponseDashboardTable, 
  IDashboardOverview, 
  IDashboardTable, 
  IDashboardTableItem 
} from '../../../models/tech-dashboards.model';
import { DEFAULT_DASHBOARD_PAGINATION } from '../../../constants/tech-dashboards.constant';

@Injectable({
  providedIn: 'root',
})
export class TechDashboardsAdapter {
  public mapDashboardOverview(response: ResponseDashboardCards): IDashboardOverview {
    if (!response) {
      return {} as IDashboardOverview;
    }

    return {
      header: response.header ?? { title: '', cutoffDate: '', lastUpdated: '', subtitle: '' },
      summaryBanner: response.summaryBanner ?? { text: '' },
      scoreThresholds: response.scoreThresholds ?? [],
      kpiCards: response.kpiCards ?? [],
      pillarComparison: response.pillarComparison ?? { cutoffDate: '', items: [] },
    };
  }

  public mapDashboardTable(response: ResponseDashboardTable): IDashboardTable {
    const safeRows = Array.isArray(response?.rows) ? response.rows : [];

    const mappedResults: IDashboardTableItem[] = safeRows.map((item) => ({
      id: item.id,
      evc: item.evc,
      score: item.score,
      scoreDisplay: item.scoreDisplay,
      vicepresidencia: item.vicepresidencia,
      dateDisplay: item.dateDisplay,
      column5: item.column5,
      column6: item.column6,
      column7: item.column7,
      column8: item.column8,
      column9: item.column9,
    }));

    return {
      count: response?.pagination?.totalItems ?? mappedResults.length,
      page: response?.pagination?.currentPage ?? DEFAULT_DASHBOARD_PAGINATION.PAGE,
      size: response?.pagination?.pageSize ?? DEFAULT_DASHBOARD_PAGINATION.LIMIT,
      columns: response?.columns ?? [],
      results: mappedResults,
    };
  }
}






















import { inject, Injectable } from '@angular/core';
import { HttpClient } from '@angular/common/http';
import { Observable, catchError, map, of } from 'rxjs';
import { environment } from 'src/environments/environment';
import { TechDashboardsAdapter } from './adapters/tech-dashboards.adapter';
import { 
  ResponseDashboardCards, 
  ResponseDashboardTable, 
  IDashboardOverview, 
  IDashboardTable, 
  IDashboardFilters 
} from '../../models/tech-dashboards.model';
import { 
  EMPTY_DASHBOARD_OVERVIEW_STATE, 
  EMPTY_DASHBOARD_TABLE_STATE 
} from '../../constants/tech-dashboards.constant';

@Injectable({
  providedIn: 'root',
})
export class TechDashboardsService {
  private readonly _http = inject(HttpClient);
  private readonly _adapter = inject(TechDashboardsAdapter);

  public getDashboardOverview(filters?: Partial<IDashboardFilters>): Observable<IDashboardOverview> {
    const url = `${environment.apiBaseUrl}/metrics/api/dashboards/cards`;

    return this._http.get<ResponseDashboardCards>(url, { params: filters as any }).pipe(
      map((values) => this._adapter.mapDashboardOverview(values)),
      catchError((error) => {
        return of(EMPTY_DASHBOARD_OVERVIEW_STATE as unknown as IDashboardOverview);
      })
    );
  }

  public getDashboardTable(filters: IDashboardFilters): Observable<IDashboardTable> {
    const url = `${environment.apiBaseUrl}/metrics/api/dashboards/table`;

    return this._http.get<ResponseDashboardTable>(url, { params: filters as any }).pipe(
      map((values) => this._adapter.mapDashboardTable(values)),
      catchError((error) => {
        return of(EMPTY_DASHBOARD_TABLE_STATE as unknown as IDashboardTable);
      })
    );
  }
}







import { Component, computed, inject, signal } from '@angular/core';
import { rxResource } from '@angular/core/rxjs-interop';
import { TechDashboardsService } from '../../../../core/services/tech-dashboards/tech-dashboards.service';
import { IDashboardFilters } from '../../../../core/models/tech-dashboards.model';
import { DEFAULT_DASHBOARD_PAGINATION } from '../../../../core/constants/tech-dashboards.constant';

import { DashboardFiltersComponent } from '../../components/dashboard-filters/dashboard-filters.component';
import { DashboardSummaryBannerComponent } from '../../components/dashboard-summary-banner/dashboard-summary-banner.component';
import { DashboardsCardsComponent } from '../../components/dashboards-cards/dashboards-cards.component';
import { DashboardBarsComponent } from '../../components/dashboard-bars/dashboard-bars.component';
import { DashboardsTableComponent } from '../../components/dashboards-table/dashboards-table.component';

@Component({
  selector: 'app-dashboard-principal',
  standalone: true,
  imports: [
    DashboardFiltersComponent,
    DashboardSummaryBannerComponent,
    DashboardsCardsComponent,
    DashboardBarsComponent,
    DashboardsTableComponent,
  ],
  templateUrl: './dashboard-principal.component.html',
  styleUrl: './dashboard-principal.component.scss',
})
export class DashboardPrincipalComponent {
  private readonly _dashboardService = inject(TechDashboardsService);

  public readonly pageSizeOptions = DEFAULT_DASHBOARD_PAGINATION.OPTIONS;

  public $filters = signal<IDashboardFilters>({
    page: DEFAULT_DASHBOARD_PAGINATION.PAGE,
    limit: DEFAULT_DASHBOARD_PAGINATION.LIMIT,
    vicepresidencia: 'Todas',
    search: '',
  });

  public resourceOverview = rxResource({
    params: () => ({ vicepresidencia: this.$filters().vicepresidencia }),
    stream: ({ params }) => this._dashboardService.getDashboardOverview(params),
  });

  public resourceTable = rxResource({
    params: () => this.$filters(),
    stream: ({ params }) => this._dashboardService.getDashboardTable(params),
  });

  public $overviewData = computed(() => this.resourceOverview.value());
  public $tableData = computed(() => this.resourceTable.value());

  public onApplyFilters(newFilters: Partial<IDashboardFilters>): void {
    this.$filters.update((current) => ({
      ...current,
      ...newFilters,
      page: DEFAULT_DASHBOARD_PAGINATION.PAGE,
    }));
  }

  public onChangePage(event: { currentPage: number; itemsPerPage: number }): void {
    this.$filters.update((current) => ({
      ...current,
      page: event.currentPage,
      limit: event.itemsPerPage,
    }));
  }
}












